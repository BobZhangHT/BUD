#!/usr/bin/env python3
"""Reproduce supplementary Sections S11--S12 from a standalone release.

This module is called by the release-root ``reproduce.py``.  It intentionally
uses subprocesses so the archived scripts retain their normal script-import
semantics and record their own source hashes.  It never edits an existing
result directory.
"""
from __future__ import annotations

from pathlib import Path
import argparse
import os
import subprocess
import sys
from time import perf_counter


ROOT = Path(__file__).resolve().parents[1]
CODE = ROOT / "code"
RESULTS = ROOT / "results"
FIGURES = ROOT / "figures"


def _run(*arguments: str) -> None:
    """Run one archived script from the standalone release root."""
    command = [sys.executable, "-B", *arguments]
    print("+", " ".join(command), flush=True)
    environment = os.environ.copy()
    environment["PYTHONUTF8"] = "1"
    subprocess.run(command, cwd=ROOT, env=environment, check=True)


def _require(path: Path, description: str) -> None:
    if not path.exists():
        raise FileNotFoundError(f"{description} is required but was not found: {path}")


def run(backend: str, workers: int, quick: bool) -> None:
    """Run S11--S12 checks and figures.

    Full mode writes the canonical release directories:
    ``results/theory_validation_20261122`` and
    ``results/budget_refresh_20261122/{fixed_grid,simulation_budget_sensitivity}``.
    Sensitivity consumes the primary confirmation raw output generated by the
    root simulation module.  Quick mode writes only an inexpensive fixed-grid
    bootstrap smoke check to ``smoke_results/supplement``; it does not make
    paper figures.
    """
    if backend not in {"c", "python"}:
        raise ValueError("backend must be 'c' or 'python'")
    if workers < 1:
        raise ValueError("workers must be positive")
    _require(CODE / "bud_experiment.py", "shared experiment launcher")
    _require(CODE / "legacy_locked" / "survival.py", "locked survival implementation")

    started = perf_counter()
    if quick:
        out = ROOT / "smoke_results" / "supplement"
        if out.exists():
            raise FileExistsError(f"Refusing to overwrite existing smoke output: {out}")
        _run("code/theory_check_bootstrap.py", "--profile", "smoke", "--out", str(out / "bootstrap"))
        print(f"Supplement smoke completed in {perf_counter() - started:.1f}s", flush=True)
        return

    theory = RESULTS / "theory_validation_20261122"
    refresh_root = RESULTS / "budget_refresh_20261122"
    fixed = refresh_root / "fixed_grid"
    sensitivity = refresh_root / "simulation_budget_sensitivity"
    anchors = refresh_root / "anchor_ablation"
    for path in (theory, fixed, sensitivity, anchors):
        if path.exists():
            raise FileExistsError(f"Refusing to overwrite existing full output: {path}")

    _run("code/theory_check_geometry.py", "--out", str(theory / "geometry.json"))
    _run("code/theory_check_bootstrap.py", "--profile", "full", "--out", str(theory / "bootstrap"))
    _run("code/theory_check_budget.py", "--out", str(theory / "budget_corrected"))
    _run("code/theory_check_conclusions.py", "--study", str(theory), "--out", str(theory / "evidence_checks.json"))
    _run("code/plot_theory_validation.py", "--study", str(theory), "--out", str(FIGURES))
    _run("code/bud_experiment.py", "fixed-grid", "--backend", backend, "--workers", str(workers),
         "--cohorts", "50", "--draws", "20", "--bootstrap-replicates", "1000", "--out", str(fixed))

    confirmation = refresh_root / "confirmation" / "raw.csv"
    _require(confirmation, "primary confirmation raw output for S12 budget sensitivity")
    _require(ROOT / "handoff" / "SIMULATION_BUDGET_SENSITIVITY_PROTOCOL.md",
             "S12 budget-sensitivity protocol")
    _require(CODE / "refresh_secondary.py", "S12 budget-sensitivity refresh driver")
    _run("code/refresh_secondary.py", "sensitivity", "--root", str(refresh_root),
         "--workers", str(workers), "--backend", backend)
    _run("code/refresh_secondary.py", "anchors", "--root", str(refresh_root),
         "--workers", str(workers), "--backend", backend)
    print(f"Supplement full run completed in {perf_counter() - started:.1f}s", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--backend", choices=("c", "python"), default="c")
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()
    run(args.backend, args.workers, args.quick)


if __name__ == "__main__":
    main()
